def stage_validate_syntax(code: str):
    print("[3/8] Validating JavaScript/ExtendScript syntax...")
    temp_file = os.path.join(WORKSPACE_ROOT, "dist", ".syntax_check.tmp.js")
    os.makedirs(os.path.dirname(temp_file), exist_ok=True)
    with open(temp_file, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)

    try:
        proc = subprocess.run(["node", "--check", temp_file], capture_output=True, text=True)
        if proc.returncode != 0:
            raise SyntaxError(f"Node.js syntax check failed:\n{proc.stderr}")
    finally:
        if os.path.exists(temp_file):
            os.remove(temp_file)
    print("  Syntax validation PASSED (Node.js engine check clean).")

class DeploymentState:
    BUILD_ONLY = "BUILD_ONLY"
    STAGED = "STAGED"
    MIRROR_ONLY = "MIRROR_ONLY"
    LIVE_INSTALLED = "LIVE_INSTALLED"
    LIVE_AND_MIRROR_VERIFIED = "LIVE_AND_MIRROR_VERIFIED"
    DEPLOY_BLOCKED = "DEPLOY_BLOCKED"
    DEPLOY_FAILED = "DEPLOY_FAILED"

def find_installed_instances(search_dirs=None) -> list:
    """Finds all existing copies of vac34_AE across standard AE script directories or specified search directories."""
    discovered = []
    if search_dirs is not None:
        base_dirs = search_dirs
    else:
        base_dirs = [
            LIVE_INSTALL_DIR,
            LIVE_INSTALL_DIR_DEFAULT,
            os.path.dirname(LIVE_INSTALL_DIR_DEFAULT),
            MIRROR_INSTALL_DIR
        ]
        appdata = os.environ.get("APPDATA")
        if appdata:
            base_dirs.extend([
                os.path.join(appdata, r"Adobe\After Effects\24.0\Scripts\ScriptUI Panels"),
                os.path.join(appdata, r"Adobe\After Effects\24.6\Scripts\ScriptUI Panels")
            ])
    seen_paths = set()
    for b in base_dirs:
        if not b or not os.path.exists(b):
            continue
        try:
            target_dir = b if os.path.isdir(b) else os.path.dirname(b)
            for fname in os.listdir(target_dir):
                if fname.lower().startswith("vac34_ae") and fname.lower().endswith(".jsx"):
                    fpath = os.path.normpath(os.path.join(target_dir, fname))
                    if fpath in seen_paths:
                        continue
                    seen_paths.add(fpath)
                    discovered.append({
                        "path": fpath,
                        "sha256": compute_sha256(fpath),
                        "size": os.path.getsize(fpath)
                    })
        except Exception:
            pass
    return discovered

def stage_write_artifacts(code: str) -> dict:
    print("[4/8] Writing release artifacts...")
    dist_dir = os.path.join(WORKSPACE_ROOT, "dist")
    release_dir = os.path.join(WORKSPACE_ROOT, "release")
    os.makedirs(dist_dir, exist_ok=True)
    os.makedirs(release_dir, exist_ok=True)

    dist_path = os.path.join(dist_dir, DIST_FILENAME)
    release_path = os.path.join(release_dir, RELEASE_FILENAME)

    # Canonical line endings normalization (strict \n across all platforms)
    canonical_code = code.replace("\r\n", "\n")
    if not canonical_code.endswith("\n"):
        canonical_code += "\n"

    with open(dist_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(canonical_code)

    with open(release_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(canonical_code)

    sha = compute_sha256(dist_path)
    file_size = os.path.getsize(dist_path)

    manifest = {
        "product": PRODUCT_NAME,
        "version": VERSION,
        "build_fingerprint": BUILD_ID,
        "sha256": sha,
        "file_size_bytes": file_size,
        "dist_file": dist_path,
        "release_file": release_path,
        "source_files": SOURCE_FILES,
        "built_at": os.environ.get("SOURCE_DATE_EPOCH_STR", "2026-11-07T12:00:00Z")
    }

    manifest_path = os.path.join(release_dir, "build_manifest.json")
    with open(manifest_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=2)

    # Deployment side effect removed on purpose: an artifact write alone must
    # never touch Live AE or the backup mirror, so a portable or clean-export
    # build stays reproducible from source bytes only. Mirror sync lives in
    # stage_deploy, behind an explicit --deploy/--install.
    if os.environ.get("VAC34_SYNC_MIRROR") == "1":
        try:
            if os.path.exists(os.path.splitdrive(MIRROR_INSTALL_DIR)[0]):
                os.makedirs(MIRROR_INSTALL_DIR, exist_ok=True)
                target_mirror = os.path.join(MIRROR_INSTALL_DIR, DIST_FILENAME)
                shutil.copy2(dist_path, target_mirror)
        except Exception:
            pass

    print(f"  Artifact generated: {dist_path} ({file_size} bytes)")
    print(f"  SHA-256: {sha}")
    return manifest

def stage_deploy(manifest: dict) -> dict:
    print("[5/8] Executing deployment transaction (Live AE + Backup Mirror)...")
    dist_path = manifest["dist_file"]
    sha = manifest["sha256"]

    deploy_results = {
        "state": DeploymentState.DEPLOY_FAILED,
        "live_installed": False,
        "mirror_installed": False,
        "hashes_match": False,
        "live_path": None,
        "mirror_path": None,
        "live_sha256": None,
        "mirror_sha256": None,
        "live_error": None,
        "mirror_error": None,
        "installed_instances": []
    }

    # 1. Live installation
    try:
        if os.path.exists(LIVE_INSTALL_DIR):
            os.makedirs(LIVE_INSTALL_DIR, exist_ok=True)
            target_live = os.path.join(LIVE_INSTALL_DIR, DIST_FILENAME)
            if os.path.exists(target_live):
                bak = target_live + ".bak"
                try:
                    shutil.copy2(target_live, bak)
                except Exception:
                    pass
            shutil.copy2(dist_path, target_live)
            live_sha = compute_sha256(target_live)
            deploy_results["live_installed"] = True
            deploy_results["live_path"] = target_live
            deploy_results["live_sha256"] = live_sha
            print(f"  Installed to Live AE: {target_live}")
        else:
            print(f"  WARNING: Live AE install dir not found: {LIVE_INSTALL_DIR}")
            deploy_results["live_error"] = f"Directory not found: {LIVE_INSTALL_DIR}"
    except PermissionError as pe:
        print(f"  WARNING: Permission denied deploying to Live AE ({LIVE_INSTALL_DIR}): {pe}")
        deploy_results["live_installed"] = False
        deploy_results["live_error"] = str(pe)
        target_live = os.path.join(LIVE_INSTALL_DIR, DIST_FILENAME)
        deploy_results["live_path"] = target_live
        if os.path.exists(target_live):
            deploy_results["live_sha256"] = compute_sha256(target_live)
    except Exception as e:
        print(f"  WARNING: Unexpected error deploying to Live AE: {e}")
        deploy_results["live_installed"] = False
        deploy_results["live_error"] = str(e)

    # 2. Recovery Mirror
    try:
        mirror_parent = os.path.dirname(MIRROR_INSTALL_DIR)
        if os.path.exists(mirror_parent) or os.path.exists(os.path.splitdrive(MIRROR_INSTALL_DIR)[0]):
            os.makedirs(MIRROR_INSTALL_DIR, exist_ok=True)
            target_mirror = os.path.join(MIRROR_INSTALL_DIR, DIST_FILENAME)
            if os.path.exists(target_mirror):
                bak = target_mirror + ".bak"
                try:
                    shutil.copy2(target_mirror, bak)
                except Exception:
                    pass
            shutil.copy2(dist_path, target_mirror)
            mirror_sha = compute_sha256(target_mirror)
            deploy_results["mirror_installed"] = True
            deploy_results["mirror_path"] = target_mirror
            deploy_results["mirror_sha256"] = mirror_sha
            print(f"  Synchronized to Mirror: {target_mirror}")
        else:
            print(f"  WARNING: Mirror parent dir not found: {MIRROR_INSTALL_DIR}")
            deploy_results["mirror_error"] = f"Mirror path not accessible: {MIRROR_INSTALL_DIR}"
    except Exception as me:
        print(f"  WARNING: Error deploying to mirror: {me}")
        deploy_results["mirror_installed"] = False
        deploy_results["mirror_error"] = str(me)

    # Determine deployment state
    if deploy_results["live_installed"] and deploy_results["mirror_installed"]:
        if deploy_results["live_sha256"] == deploy_results["mirror_sha256"] == sha:
            deploy_results["state"] = DeploymentState.LIVE_AND_MIRROR_VERIFIED
            deploy_results["hashes_match"] = True
            print("  [VERIFIED] Live and Mirror hashes are byte-identical!")
        else:
            deploy_results["state"] = DeploymentState.DEPLOY_FAILED
            deploy_results["hashes_match"] = False
            print("  WARNING: Hash mismatch between Live and Mirror artifacts!")
    elif deploy_results["mirror_installed"] and not deploy_results["live_installed"]:
        if deploy_results.get("live_error") and "Permission denied" in str(deploy_results.get("live_error")):
            deploy_results["state"] = DeploymentState.DEPLOY_BLOCKED
            print("  [DEPLOY_BLOCKED] Mirror installed, but Live AE locked by OS permissions.")
        else:
            deploy_results["state"] = DeploymentState.MIRROR_ONLY
            print("  [MIRROR_ONLY] Mirror installed, but Live AE not installed.")
    elif deploy_results["live_installed"] and not deploy_results["mirror_installed"]:
        deploy_results["state"] = DeploymentState.LIVE_INSTALLED
        print("  [LIVE_INSTALLED] Live AE installed, but Mirror not synchronized.")
    else:
        deploy_results["state"] = DeploymentState.DEPLOY_FAILED
        print("  [DEPLOY_FAILED] Neither Live nor Mirror could be installed.")

    deploy_results["installed_instances"] = find_installed_instances()

    # Save deployment report
    log_dir = os.path.join(WORKSPACE_ROOT, "logs")
    os.makedirs(log_dir, exist_ok=True)
    report_path = os.path.join(log_dir, "deployment_report.json")
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(deploy_results, f, indent=2)

    return deploy_results

def stage_run_tests():
    print("[6/8] Running automated test suite...")
    test_proc = subprocess.run(
        [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-p", "test_*.py"],
        cwd=WORKSPACE_ROOT,
        capture_output=True,
        text=True
    )
    if test_proc.returncode != 0:
        print(test_proc.stdout)
        print(test_proc.stderr)
        raise RuntimeError("Unit test suite FAILED.")
    print("  All unit, hardening, and scenario tests PASSED.")

def stage_verify_installation(deploy_results: dict, manifest: dict = None) -> bool:
    print("[7/8] Verifying deployed files...")
    state = deploy_results.get("state")
    if state == DeploymentState.DEPLOY_BLOCKED:
        err = deploy_results.get("live_error", "Permission denied")
        print(f"  [DEPLOY_BLOCKED] Live AE installation failed: {err}")
        print("  Execute elevated install: run scripts/install_admin.cmd or run 'python scripts/manage.py repair-mirror' as Administrator.")
        raise PermissionError(f"Deployment BLOCKED: Live AE installation failed ({err}).")
    elif state == DeploymentState.MIRROR_ONLY:
        raise RuntimeError(f"Deployment INCOMPLETE (MIRROR_ONLY): Live not installed: {deploy_results.get('live_error')}")
    elif state == DeploymentState.LIVE_INSTALLED:
        raise RuntimeError(f"Deployment INCOMPLETE (LIVE_INSTALLED): Mirror not synchronized: {deploy_results.get('mirror_error')}")
    elif state != DeploymentState.LIVE_AND_MIRROR_VERIFIED:
        raise RuntimeError(f"Deployment FAILED: state={state}, live={deploy_results.get('live_installed')}, mirror={deploy_results.get('mirror_installed')}")

    # Physical file presence
    live_path = deploy_results.get("live_path")
    mirror_path = deploy_results.get("mirror_path")
    if not live_path or not os.path.exists(live_path):
        raise RuntimeError(f"Deployment verification FAILED: Live file does not exist at {live_path}")
    if not mirror_path or not os.path.exists(mirror_path):
        raise RuntimeError(f"Deployment verification FAILED: Mirror file does not exist at {mirror_path}")

    # Physical file size check
    live_size = os.path.getsize(live_path)
    mirror_size = os.path.getsize(mirror_path)
    if live_size < 5000 or mirror_size < 5000:
        raise RuntimeError(f"Deployment verification FAILED: File size abnormally small (live={live_size}, mirror={mirror_size})")

    # Read physical headers
    with open(live_path, "r", encoding="utf-8", errors="replace") as f:
        live_head = f.read(2048)
    with open(mirror_path, "r", encoding="utf-8", errors="replace") as f:
        mirror_head = f.read(2048)
    if "vac34" not in live_head or "vac34" not in mirror_head:
        raise RuntimeError("Deployment verification FAILED: File content does not contain vac34 signature.")

    # Manifest verification
    manifest_path = os.path.join(WORKSPACE_ROOT, "release", "build_manifest.json")
    if manifest is None and os.path.exists(manifest_path):
        try:
            with open(manifest_path, "r", encoding="utf-8") as f:
                manifest = json.load(f)
        except Exception:
            manifest = None

    expected_sha = None
    if manifest and "sha256" in manifest:
        expected_sha = manifest["sha256"]
    else:
        expected_sha = actual_live_sha

    # Re-calculate real SHA-256 directly from disk (Do NOT trust deploy_results flags!)
    actual_live_sha = compute_sha256(live_path)
    actual_mirror_sha = compute_sha256(mirror_path)

    if actual_live_sha != actual_mirror_sha:
        raise RuntimeError(f"Deployment verification FAILED: Live and Mirror hashes differ (live={actual_live_sha}, mirror={actual_mirror_sha})")

    if actual_live_sha != expected_sha:
        raise RuntimeError(f"Deployment verification FAILED: Live SHA ({actual_live_sha}) does not match manifest SHA ({expected_sha})")

    # BUILD_ID inside the installed artifact must equal the manifest fingerprint
    if manifest and "build_fingerprint" in manifest:
        expected_build_id = manifest["build_fingerprint"]
        with open(live_path, "r", encoding="utf-8", errors="replace") as f:
            live_full = f.read()
        marker = 'BUILD_ID: "' + expected_build_id + '"'
        if marker not in live_full:
            raise RuntimeError(
                f"Deployment verification FAILED: installed BUILD_ID does not match manifest fingerprint {expected_build_id}"
            )

    dist_path = (manifest.get("dist_file") if manifest else None) or os.path.join(WORKSPACE_ROOT, "dist", DIST_FILENAME)
    if manifest and os.path.exists(dist_path):
        actual_dist_sha = compute_sha256(dist_path)
        if actual_dist_sha != actual_live_sha:
            raise RuntimeError(f"Deployment verification FAILED: Dist SHA ({actual_dist_sha}) does not match Live SHA ({actual_live_sha})")

    print(f"  [PASS] Filesystem verification PASSED: Live ({actual_live_sha[:8]}...) and Mirror ({actual_mirror_sha[:8]}...) match release SHA-256.")
    return True

def main():
    deploy_flag = "--deploy" in sys.argv or "--install" in sys.argv
    skip_tests = "--no-tests" in sys.argv or os.environ.get("VAC34_BUILD_NO_TESTS") == "1"
    print(f"=== vac34_AE Build System (v{VERSION}) ===")
    
    stage_validate_sources()
    bundle_code = stage_bundle()
    stage_validate_syntax(bundle_code)
    manifest = stage_write_artifacts(bundle_code)

    if not skip_tests:
        stage_run_tests()

    if deploy_flag:
        deploy_results = stage_deploy(manifest)
        try:
            stage_verify_installation(deploy_results, manifest)
        except PermissionError as pe:
            print(f"\n[BUILD STOPPED / DEPLOY_BLOCKED] {pe}")
            sys.exit(2)
        except Exception as e:
            print(f"\n[BUILD STOPPED / DEPLOY_FAILED] {e}")
            sys.exit(1)
    else:
        print("  Build completed without --deploy (state: BUILD_ONLY). Run with --deploy to install.")

    print("[8/8] Build process finished SUCCESSFULLY.")

if __name__ == "__main__":
    main()
