def discover_ae_install_dir() -> str:
    """Discovers real After Effects 2024 installation path using registry and filesystem checks."""
    candidates = []

    # 1. Check Windows Registry for App Paths
    try:
        import winreg
        for root_key in (winreg.HKEY_LOCAL_MACHINE, winreg.HKEY_CURRENT_USER):
            for subkey in (
                r"Software\Microsoft\Windows\CurrentVersion\App Paths\AfterFX.exe",
                r"Software\Adobe\After Effects\24.0",
            ):
                try:
                    with winreg.OpenKey(root_key, subkey) as key:
                        for val_name in ("Path", "InstallPath", ""):
                            try:
                                val, _ = winreg.QueryValueEx(key, val_name)
                                if val and os.path.exists(val):
                                    candidates.append(val)
                            except OSError:
                                pass
                except OSError:
                    pass
    except ImportError:
        pass

    # 2. Check standard drive locations
    for drive in ("C:", "D:", "E:", "V:"):
        candidates.append(os.path.join(drive, r"\Program Files\Adobe\Adobe After Effects 2024\Support Files"))

    for cand in candidates:
        if not cand:
            continue
        cand_clean = cand.strip().rstrip("\\/")
        panels_dir = os.path.join(cand_clean, "Scripts", "ScriptUI Panels")
        if os.path.exists(panels_dir):
            return panels_dir
        if os.path.exists(cand_clean) and cand_clean.lower().endswith("scriptui panels"):
            return cand_clean

    return LIVE_INSTALL_DIR_DEFAULT

LIVE_INSTALL_DIR = discover_ae_install_dir()

def compute_sha256(filepath: str) -> str:
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(8192):
            h.update(chunk)
    return h.hexdigest()

def stage_validate_sources():
    print("[1/8] Validating source tree...")
    for rel_path in SOURCE_FILES:
        full_path = os.path.join(WORKSPACE_ROOT, rel_path)
        if not os.path.exists(full_path):
            raise FileNotFoundError(f"Missing required source file: {full_path}")
    print("  All source files verified present.")

def compute_source_fingerprint() -> str:
    """Automatic build identity: digest over product version + every bundled
    source file's bytes. Changes in any source file change BUILD_ID, so two
    builds are only identical when their sources are identical."""
    h = hashlib.sha256()
    h.update(PRODUCT_NAME.encode("utf-8"))
    h.update(b"\x00")
    h.update(VERSION.encode("utf-8"))
    for rel_path in SOURCE_FILES:
        full_path = os.path.join(WORKSPACE_ROOT, rel_path)
        with open(full_path, "rb") as f:
            h.update(rel_path.encode("utf-8"))
            h.update(b"\x00")
            h.update(f.read())
    return h.hexdigest()

BUILD_ID = f"{VERSION}+{compute_source_fingerprint()[:12]}"

