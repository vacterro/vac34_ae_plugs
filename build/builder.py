    bundle_lines.append("        thisObj.vac34_PresetManager = vac34_PresetManager;")
    bundle_lines.append("        thisObj.vac34_Diagnostics = vac34_Diagnostics;")
    bundle_lines.append("        thisObj.vac34_Engine = vac34_Engine;")
    bundle_lines.append("        thisObj.vac34_UIBuilder = vac34_UIBuilder;")
    bundle_lines.append("    }")
    bundle_lines.append("    var _glob = (typeof global !== 'undefined') ? global : ((typeof $.global !== 'undefined') ? $.global : ((typeof window !== 'undefined') ? window : null));")
    bundle_lines.append("    if (_glob) {")
    bundle_lines.append("        _glob.vac34_Config = vac34_Config;")
    bundle_lines.append("        _glob.vac34_AEDom = vac34_AEDom;")
    bundle_lines.append("        _glob.vac34_TargetResolver = vac34_TargetResolver;")
